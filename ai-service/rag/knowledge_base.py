def retrieve_knowledge(disease: str, crop_type: str) -> dict:
    """
    知识检索（模拟 RAG）
    1. 精确匹配 → 2. 模糊匹配（关键词交集） → 3. 兜底
    """
    # 精确匹配
    result = KNOWLEDGE_BASE.get(disease)
    if result:
        return result

    # 模糊匹配：查疾病名的关键词是否出现在知识库的key中
    for key, val in KNOWLEDGE_BASE.items():
        key_words = key.replace(crop_type, "").replace("病", "")
        if key_words and key_words in disease:
            return val
        if disease.replace(crop_type, "") in key:
            return val

